"""Generate dependency_map.json from the code's real imports, so the map the chat reads cannot drift.

python3 scripts/dependency-map.py          rewrite the map
python3 scripts/dependency-map.py --check  fail when the committed map is stale
"""
import json
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.diagnostics import run

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "dependency_map.json"
PY_IMPORT = re.compile(r"^\s*(?:from\s+((?:engine|tools)(?:\.\w+)+)\s+import|import\s+((?:engine|tools)(?:\.\w+)+))", re.M)
JS_IMPORT = re.compile(r"""^\s*import\s+(?:[^'"]*?\s+from\s+)?['"](\.{1,2}/[^'"]+)['"]""", re.M)


def rel(path):
    return path.relative_to(ROOT).as_posix()


def python_modules():
    modules = {}
    tests = {p: p.read_text() for p in sorted((ROOT / "tests").glob("test_*.py"))}
    for path in sorted([*(ROOT / "engine").glob("*.py"), *(ROOT / "tools").glob("*.py")]):
        if path.name == "__init__.py":
            continue
        dotted = rel(path)[:-3].replace("/", ".")
        found = {m[0] or m[1] for m in PY_IMPORT.findall(path.read_text())}
        depends = sorted({name.replace(".", "/") + ".py" for name in found if (ROOT / (name.replace(".", "/") + ".py")).exists()} - {rel(path)})
        users = sorted(rel(t) for t, text in tests.items() if re.search(r"\b" + re.escape(dotted) + r"\b", text))
        modules[rel(path)] = (depends, users)
    return modules


def javascript_modules():
    modules = {}
    tests = {p: p.read_text() for p in sorted((ROOT / "tests").glob("*.mjs"))}
    for path in sorted((ROOT / "chat-backend/src").glob("*.js")):
        depends = sorted(rel((path.parent / spec).resolve()) for spec in JS_IMPORT.findall(path.read_text()))
        users = sorted(rel(t) for t, text in tests.items() if rel(path) in text or path.name in text)
        modules[rel(path)] = (depends, users)
    html = (ROOT / "preview/index.html").read_text()
    scripts = ["preview/" + s for s in re.findall(r'<script src="\./([\w.-]+\.js)\?v=', html)]
    modules["preview/index.html"] = (scripts, [])
    modules["ios/KappaForge/KappaWebView.swift"] = (["ios/KappaForge/Web/ (generated by scripts/bundle-web.py)"], [])
    return modules


def build():
    modules = {**python_modules(), **javascript_modules()}
    return {
        "schema_version": 2,
        "repository": "onlykappa/KappaForge",
        "generated_by": "scripts/dependency-map.py",
        "modules": [{"path": p, "depends_on": d, **({"tests": t} if t else {})} for p, (d, t) in sorted(modules.items())],
    }


# The Worker hands the model only the first 6000 characters of the map; a longer file would be cut mid-JSON.
BUDGET = 5999


def compact(data, modules, omitted):
    # Paths occur in many import and test edges. Index them once.
    paths = sorted({path for path, _, _ in modules} | {p for _, depends, tests in modules for p in (*depends, *tests)})
    index = {path: n for n, path in enumerate(paths)}
    out = dict(schema_version=3, repository=data['repository'], generated_by=data['generated_by'],
               columns=['path_index', 'dependency_indices', 'test_indices'], paths=paths,
               modules=[[index[path], [index[p] for p in depends], [index[p] for p in tests]] for path, depends, tests in modules])
    if omitted:
        out['omitted'] = omitted
    return json.dumps(out, separators=(',', ':')) + '\n'


def render(data, budget=BUDGET):
    """The whole map when it fits the budget; otherwise drop test links, then dependency links, from the modules with
    the most links first, and say how many were left out. The result is always complete, valid JSON."""
    modules = [[m['path'], list(m['depends_on']), list(m.get('tests', []))] for m in data['modules']]
    dropped = {'test_links': 0, 'dependency_links': 0}
    for column, key in ((2, 'test_links'), (1, 'dependency_links')):
        while True:
            omitted = {**{k: v for k, v in dropped.items() if v},
                       'note': 'Links left out to fit the chat context; read the code for the full picture.'} if any(dropped.values()) else None
            text = compact(data, modules, omitted)
            if len(text) <= budget:
                return text
            largest = max(modules, key=lambda m: len(m[column]))
            if not largest[column]:
                break
            dropped[key] += len(largest[column])
            largest[column] = []
    raise ValueError(f"dependency map cannot fit {budget} characters even without links")


def main():
    text = render(build())
    if sys.argv[1:] == ["--check"]:
        if MAP.read_text() != text:
            raise ValueError("dependency_map.json is stale; run python3 scripts/dependency-map.py")
        print("dependency_map.json matches the code")
        return
    MAP.write_text(text)
    print(f"Wrote {rel(MAP)} ({len(text)} characters)")


if __name__ == "__main__":
    sys.exit(run(main, "dependency-map"))
