"""Generate standard tool/version files from config/app.json; --check rejects drift."""
import argparse
import json
from pathlib import Path
import re
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from tools.build_config import ROOT, load_config
from tools.diagnostics import run


def generated(config):
    source=ROOT/config['webSource']
    metadata={key:config[key] for key in ['version','released','notes']}
    public={key:config[key] for key in ['version','repository','iosBundleIdentifier']}
    files={source/'version.json':json.dumps(metadata,indent=2)+'\n',
           source/'app-config.js':'// Generated by scripts/configure.py. Edit config/app.json.\n'+'globalThis.KappaConfig=Object.freeze('+json.dumps(public,separators=(',',':'))+');\n',
           ROOT/'.nvmrc':config['nodeVersion']+'\n',ROOT/'.python-version':config['pythonVersion']+'\n'}
    html=(source/'index.html').read_text()
    html=re.sub(r'\?v=\d+\.\d+\.\d+', '?v='+config['version'],html)
    files[source/'index.html']=html
    project=ROOT/'ios/project.yml'
    text=project.read_text()
    text=re.sub(r"MARKETING_VERSION: '[^']+'", "MARKETING_VERSION: '"+config['version']+"'",text)
    text=re.sub(r'PRODUCT_BUNDLE_IDENTIFIER: [^\n]+',lambda m:'PRODUCT_BUNDLE_IDENTIFIER: '+config['iosBundleIdentifier']+('.UITests' if m[0].endswith('.UITests') else ''),text)
    files[project]=text
    for name in ['package.json','chat-backend/package.json']:
        path=ROOT/name;data=json.loads(path.read_text());data['version']=config['version'];files[path]=json.dumps(data,indent=2)+'\n'
        lock=path.with_name('package-lock.json');data=json.loads(lock.read_text());data['version']=config['version'];data['packages']['']['version']=config['version'];files[lock]=json.dumps(data,indent=2)+'\n'
    return files


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    drift=[]
    for path,body in generated(load_config()).items():
        if not path.exists() or path.read_text()!=body:
            if args.check:drift.append(str(path.relative_to(ROOT)))
            else:path.write_text(body)
    if drift:raise ValueError('Generated build settings differ: '+', '.join(drift)+'. Run python scripts/configure.py.')
    print('Build settings '+('verified' if args.check else 'generated')+' from config/app.json')

if __name__=='__main__':sys.exit(run(main,'configuration'))
